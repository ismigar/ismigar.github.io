export function translate(
  locale: DashboardLocale,
  key: string,
  values: Record<string, string | number> = {},
): string {
  const template = translations[locale][key] ?? translations.en[key] ?? key;
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function translationKeyParity(): string[] {
  const reference = new Set(Object.keys(translations.en));
  return dashboardLocales.flatMap((locale) => {
    const keys = new Set(Object.keys(translations[locale]));
    return [
      ...[...reference].filter((key) => !keys.has(key)).map((key) => `${locale}:missing:${key}`),
      ...[...keys].filter((key) => !reference.has(key)).map((key) => `${locale}:extra:${key}`),
    ];
  });
}
